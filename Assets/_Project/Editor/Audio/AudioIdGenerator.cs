#if UNITY_EDITOR
using UnityEngine;
using UnityEditor;
using System.IO;
using System.Text;
using System.Collections.Generic;

public static class AudioIdGenerator
{
    // Where the generated enum lives (must be a normal Assets/ folder, not Editor/)
    public const string OutputPath = "Assets/_Project/Infrastructure/Runtime/Audio/Generated/AudioId.cs";

    /// <summary>Regenerates AudioId.cs from a library's clips. Returns true if the file changed.</summary>
    public static bool Regenerate(AudioLibrary library)
    {
        if (library == null || library.clips == null)
            return false;

        var usedNames = new HashSet<string>();
        var entries = new List<string>();

        foreach (var clip in library.clips)
        {
            if (clip == null) continue;

            string id = SanitizeIdentifier(clip.name);
            if (string.IsNullOrEmpty(id)) continue;

            string final = id;
            int suffix = 2;
            while (!usedNames.Add(final))
                final = $"{id}_{suffix++}";

            entries.Add(final);
        }

        entries.Sort(System.StringComparer.OrdinalIgnoreCase);

        string content = BuildFile(entries);
        string current = File.Exists(OutputPath) ? File.ReadAllText(OutputPath) : null;

        if (current == content)
            return false;

        Directory.CreateDirectory(Path.GetDirectoryName(OutputPath));
        File.WriteAllText(OutputPath, content, new UTF8Encoding(false));
        AssetDatabase.ImportAsset(OutputPath);
        Debug.Log($"[AudioIdGenerator] Regenerated {OutputPath} with {entries.Count} entries.");
        return true;
    }

    private static string BuildFile(List<string> entries)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine("//     Generated by AudioIdGenerator from AudioLibrary.");
        sb.AppendLine("//     Do not edit by hand — changes will be overwritten.");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine();
        
        sb.AppendLine("public enum AudioId");
        sb.AppendLine("{");

        for (int i = 0; i < entries.Count; i++)
            sb.AppendLine($"    {entries[i]} = {i},");

        sb.AppendLine("}");
        
        return sb.ToString();
    }

    /// <summary>Turn arbitrary clip names into valid C# identifiers.</summary>
    private static string SanitizeIdentifier(string raw)
    {
        if (string.IsNullOrWhiteSpace(raw)) return null;

        var sb = new StringBuilder(raw.Length);
        foreach (char c in raw)
            sb.Append(char.IsLetterOrDigit(c) ? c : '_');

        string s = sb.ToString().Trim('_');

        while (s.Contains("__")) s = s.Replace("__", "_");

        if (s.Length == 0) return null;

        if (char.IsDigit(s[0])) s = "_" + s;
        
        if (s == "None") s = "None_";

        return s;
    }
}
#endif
